-- Salon database setup
-- Creates the tables and fills them with sample data.
-- Run with:  sqlite3 salon.db < salon_setup.sql

DROP TABLE IF EXISTS appointments;
DROP TABLE IF EXISTS clients;
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS stylists;

CREATE TABLE stylists (
  stylist_id   INTEGER PRIMARY KEY,
  name         TEXT NOT NULL,
  role         TEXT,
  hire_date    TEXT
);

CREATE TABLE services (
  service_id   INTEGER PRIMARY KEY,
  name         TEXT NOT NULL,
  category     TEXT,
  price        REAL,
  duration_min INTEGER
);

CREATE TABLE clients (
  client_id    INTEGER PRIMARY KEY,
  first_name   TEXT,
  last_name    TEXT,
  email        TEXT,
  source       TEXT,   -- how the client found the salon
  joined_date  TEXT
);

CREATE TABLE appointments (
  appointment_id INTEGER PRIMARY KEY,
  client_id      INTEGER REFERENCES clients(client_id),
  stylist_id     INTEGER REFERENCES stylists(stylist_id),
  service_id     INTEGER REFERENCES services(service_id),
  appt_date      TEXT,
  appt_time      TEXT,
  status         TEXT,   -- Completed, Cancelled or No-show
  tip            REAL
);

